// 100 civics (history and government) questions for the U.S. naturalization test
// (2008 version). Source: USCIS. Official acceptable answers are preserved verbatim
// in `acceptableAnswers`. The A/B/C/D `distractors` are study aids written for this
// app (USCIS does not publish wrong answers) and are plausible-but-incorrect options
// drawn from the same civics domain.
//
// Questions about current officials or the applicant's own state ("Who is your
// Senator?", "Who is the President now?") have no fixed answer, so they are modeled
// as `spoken` cards: the applicant practices saying the answer out loud, then sees
// the official USCIS guidance.

export type QuestionType = "choice" | "spoken";

export interface Question {
  id: number;
  category: string;
  question: string;
  type: QuestionType;
  /** Marked with * in the USCIS list: the 20-question subset for applicants 65+ with 20+ years as a permanent resident. */
  senior: boolean;
  /** All officially acceptable answers, shown on reveal. */
  acceptableAnswers: string[];
  /** choice questions: the single option displayed as correct. */
  correct?: string;
  /** choice questions: three incorrect options. */
  distractors?: string[];
  /** spoken questions: guidance shown after the applicant answers out loud. */
  guidance?: string;
  /** Optional note shown on reveal — e.g. "current answer, may change after an election". */
  note?: string;
}

